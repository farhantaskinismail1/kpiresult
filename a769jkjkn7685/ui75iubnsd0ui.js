function parseResults(dataString) {
  const results = [];
  const entries = dataString.split(/(?=\d{6}\s)/);

  for (const entry of entries) {
    const trimmedEntry = entry.trim();
    if (!trimmedEntry) continue;

    const rollMatch = trimmedEntry.match(/^(\d+)/);
    if (!rollMatch) continue;

    const roll = rollMatch[1];
    const student = { roll: roll };

    const fullEntry = trimmedEntry.replace(/\n/g, ' ');

    const gpaMatches = fullEntry.matchAll(/gpa(\d+):\s*([\d.]+|ref)/gi);
    for (const match of gpaMatches) {
      const semNum = match[1];
      const gpaValue = match[2].toLowerCase();
      student[`gpa${semNum}`] =
        gpaValue === 'ref' ? 'ref' : parseFloat(gpaValue);
    }

    const refSubMatch = fullEntry.match(/ref_sub:\s*(.+?)(?:\s*[)}\]]\s*$)/i);
    if (refSubMatch) {
      let refSubText = refSubMatch[1].trim();
      student.ref_sub_raw = refSubText;
    }

    results.push(student);
  }

  return results;
}

