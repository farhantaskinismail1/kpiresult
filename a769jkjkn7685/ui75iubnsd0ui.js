function searchResult() {
  const rollInput = document.getElementById('rollInput').value.trim();
  const resultContainer = document.getElementById('resultContainer');
  const downloadPdfBtn = document.getElementById('downloadPdfBtn');

  downloadPdfBtn.style.display = 'none';
  resultContainer.innerHTML = '';

  if (rollInput === '') {
    resultContainer.innerHTML =
      '<p class="error-message">দয়া করে রোল নম্বর দিন।</p>';
    return;
  }

  // Google Sheets এ roll number পাঠান
  sendToGoogleSheets(rollInput);

  const result = studentResults.find((student) => student.roll === rollInput);

  if (result) {
    const gpaData = [];
    let totalGpa = 0;
    let validGpaCount = 0;
    let hasRef = false;

    for (let i = 1; ; i++) {
      const gpaKey = `gpa${i}`;
      if (result[gpaKey] === undefined) break;

      const gpaValue = result[gpaKey];
      const isRef =
        typeof gpaValue === 'string' && gpaValue.toLowerCase() === 'ref';

      gpaData.push({
        semester: getSemesterName(i),
        value: isRef
          ? 'REF'
          : typeof gpaValue === 'number'
          ? gpaValue.toFixed(2)
          : parseFloat(gpaValue).toFixed(2),
        isRef: isRef,
      });

      if (!isRef) {
        totalGpa +=
          typeof gpaValue === 'number' ? gpaValue : parseFloat(gpaValue);
        validGpaCount++;
      } else {
        hasRef = true;
      }
    }

    const averageGpa =
      validGpaCount > 0 && !hasRef
        ? (totalGpa / validGpaCount).toFixed(2)
        : hasRef
        ? 'N/A (Referred)'
        : 'N/A';

    let refSubHTML = '';
    if (result.ref_sub_raw) {
      const refSubjects = result.ref_sub_raw.split(',').map((sub) => {
        let cleaned = sub.trim();
        cleaned = cleaned.replace(/\(T\)/gi, ' (Theory)');
        cleaned = cleaned.replace(/\(P\)/gi, ' Practical');
        return cleaned;
      });

      const refSubItemsHTML = refSubjects
        .map((sub) => `<span class="ref-subject-item">${sub}</span>`)
        .join('');

      refSubHTML = `
        <div class="ref-subjects-section">
          <h4>Referred Subjects</h4>
          <div class="ref-subjects-list">
            ${refSubItemsHTML}
          </div>
        </div>
      `;
    }

    let resultHTML = `
      <div id="resultContent">
        <h2 class="student_res" style="text-align: center; color: #6921ef; margin-bottom: 5px;">শিক্ষার্থীর রেজাল্ট</h2>
        <h3 class="student_roll" style="text-align: center; margin-top: 0; padding-bottom: 10px; border-bottom: 2px solid #007bff;">রোল নম্বর: ${
          result.roll
        }</h3>
        <table class="result-table" style="width: 100%; border-collapse: collapse; margin-top: 15px;">
          <thead>
            <tr style="background-color: #f2f2f2;">
              <th class="first_th" style="border: 1px solid #ddd; padding: 10px; text-align: left;">সেমিস্টার</th>
              <th class="second_th" style="border: 1px solid #ddd; padding: 10px; text-align: left;">GPA</th>
            </tr>
          </thead>
          <tbody>
            ${gpaData
              .map(
                (data) => `<tr>
                  <td style="border: 1px solid #ddd; padding: 10px;">${
                    data.semester
                  }</td>
                  <td style="${
                    data.isRef ? 'color:red;font-weight:bold;' : ''
                  } border:1px solid #ddd; padding:10px;">${data.value}</td>
                </tr>`
              )
              .join('')}
            <tr style="display:none; font-weight: bold; background-color: #e6f7ff;">
              <td style="border: 1px solid #ddd; padding: 10px;">গড় GPA (Average)</td>
              <td style="border: 1px solid #ddd; padding: 10px;">${averageGpa}</td>
            </tr>
          </tbody>
        </table>
        ${refSubHTML}
      </div>`;

    resultContainer.innerHTML = resultHTML;
    downloadPdfBtn.style.display = 'block';
  } else {
    resultContainer.innerHTML = `<p class="error-message">দুঃখিত! রোল নম্বর "${rollInput}" এর কোনো রেজাল্ট পাওয়া যায়নি।</p>`;
  }
}

function downloadResultAsPdf() {
  const element = document.querySelector('.result-container');
  if (!element) {
    alert('PDF তৈরির জন্য কোনো রেজাল্ট ডেটা পাওয়া যায়নি।');
    return;
  }

  const { jsPDF } = window.jspdf;

  window.scrollTo(0, 0);

  html2canvas(element, {
    scale: 2,
    backgroundColor: '#ffffff',
    scrollX: 0,
    scrollY: -window.scrollY,
    useCORS: true,
    height: element.scrollHeight,
    logging: false,
  }).then((canvas) => {
    const imgData = canvas.toDataURL('image/png');
    const pdf = new jsPDF('p', 'mm', 'a4');
    const pageWidth = pdf.internal.pageSize.getWidth();
    const pageHeight = pdf.internal.pageSize.getHeight();
    const imgProps = pdf.getImageProperties(imgData);
    let pdfWidth = pageWidth;
    let pdfHeight = (imgProps.height * pdfWidth) / imgProps.width;
    if (pdfHeight > pageHeight) {
      const scale = pageHeight / pdfHeight;
      pdfWidth *= scale;
      pdfHeight *= scale;
    }
    const x = (pageWidth - pdfWidth) / 2;
    const y = 0;
    pdf.addImage(imgData, 'PNG', x, y, pdfWidth, pdfHeight);
    const filename =
      'Student_Result_' +
      document.getElementById('rollInput').value.trim() +
      '.pdf';
    pdf.save(filename);
  });
}

